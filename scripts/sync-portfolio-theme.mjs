import { readFile, writeFile, mkdir, cp } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const sourceIndex=process.argv.indexOf('--source');
if(sourceIndex>=0){
 if(!process.argv[sourceIndex+1])throw Error('--source needs a directory path');
 const source=path.resolve(process.argv[sourceIndex+1]);
 for(const name of ['tokens.css','tokens.json','TOKENS.md','PATTERNS.md','provenance.json'])await cp(path.join(source,name),path.join(root,'design-system',name));
}
const source=await readFile(path.join(root,'design-system/tokens.css'),'utf8');
const css='/* Generated by scripts/sync-portfolio-theme.mjs; source design-system/tokens.css. */\n'+source.replace(/--[a-z][a-z0-9-]*/g,name=>'--portfolio-'+name.slice(2));
await mkdir(path.join(root,'assets/design-system'),{recursive:true});
await writeFile(path.join(root,'assets/design-system/portfolio-tokens.css'),css);
console.log('Generated namespaced portfolio tokens with original values preserved.');
